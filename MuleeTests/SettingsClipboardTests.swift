import Foundation
import Testing
@testable import Mulee

@Suite @MainActor struct SettingsClipboardTests {
    private final class Pasteboard: ClipboardReading {
        private var revision = 0
        var changeCount: Int {
            get {
                countReads += 1
                return revision
            }
            set { revision = newValue }
        }
        var typeNames: Set<String> = ["public.utf8-plain-text"]
        var text = "https://example.org/file.zip"
        var reads = 0
        var countReads = 0
        func plainText() -> String? {
            reads += 1
            return text
        }
    }

    @Test func onlyReadsChangedPlainTextAndPromptsOnce() {
        let pasteboard = Pasteboard()
        var prompts = 0
        let watcher = ClipboardWatcher(pasteboard: pasteboard) { _ in prompts += 1 }
        watcher.poll()
        #expect(pasteboard.reads == 0)
        #expect(pasteboard.countReads == 0)
        watcher.setEnabled(true)
        defer { watcher.setEnabled(false) }
        watcher.poll()
        #expect(pasteboard.reads == 0)
        pasteboard.changeCount += 1
        watcher.poll()
        watcher.poll()
        #expect(pasteboard.reads == 1)
        #expect(prompts == 1)
        pasteboard.changeCount += 1
        watcher.poll()
        #expect(prompts == 1)
        watcher.setEnabled(false)
        pasteboard.changeCount += 1
        let countReads = pasteboard.countReads
        watcher.poll()
        #expect(pasteboard.reads == 2)
        #expect(pasteboard.countReads == countReads)
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.cqagc.mulee.clipboard"])
    func sensitiveAndSelfWrittenContentIsNeverRead(_ marker: String) {
        let pasteboard = Pasteboard()
        let watcher = ClipboardWatcher(pasteboard: pasteboard) { _ in Issue.record("不应提示") }
        watcher.setEnabled(true)
        defer { watcher.setEnabled(false) }
        pasteboard.typeNames.insert(marker)
        pasteboard.changeCount += 1
        watcher.poll()
        #expect(pasteboard.reads == 0)
        pasteboard.typeNames = ["public.html"]
        pasteboard.changeCount += 1
        watcher.poll()
        #expect(pasteboard.reads == 0)
    }

    @Test func recognizesDownloadsButNotOrdinaryPages() {
        let text = """
        https://example.org/about https://example.org/a.ZIP?token=1
        https://example.org/a.torrent https://youtu.be/fictional
        magnet:?xt=urn:btih:0123456789012345678901234567890123456789
        ed2k://|file|fictional.zip|123|0123456789ABCDEF0123456789ABCDEF|/
        """
        #expect(ClipboardWatcher.downloadLinks(in: text).count == 5)
        #expect(ClipboardWatcher.downloadLinks(in: "https://example.org/about ftp://example.org/a.zip").isEmpty)
        #expect(ClipboardWatcher.downloadLinks(in: "file:///tmp/fictional.torrent").count == 1)
        let encoded = Data("AAhttps://example.org/downloadZZ".utf8).base64EncodedString()
        #expect(ClipboardWatcher.downloadLinks(in: "thunder://" + encoded).count == 1)
    }
}

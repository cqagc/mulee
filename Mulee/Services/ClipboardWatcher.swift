import CryptoKit
import Foundation
import MuleeCore

/// 不保存剪贴板原文；摘要仅用于本次运行去重，关闭时不访问剪贴板。
final class ClipboardWatcher {
    private let pasteboard: any ClipboardReading
    private let prompt: ([ParsedLink]) -> Void
    private var worker: Task<Void, Never>?
    private var lastChange: Int?
    private var seen: Set<SHA256.Digest> = []
    private(set) var isEnabled = false

    init(pasteboard: any ClipboardReading = SystemClipboard(), prompt: @escaping ([ParsedLink]) -> Void) {
        self.pasteboard = pasteboard
        self.prompt = prompt
    }

    isolated deinit { worker?.cancel() }

    func setEnabled(_ enabled: Bool) {
        guard enabled != isEnabled else { return }
        isEnabled = enabled
        worker?.cancel()
        worker = nil
        guard enabled else { return }
        // 不检查启用之前复制的内容。
        lastChange = pasteboard.changeCount
        worker = Task { [weak self] in
            while !Task.isCancelled {
                do { try await Task.sleep(for: .seconds(1)) }
                catch { return }
                self?.poll()
            }
        }
    }

    func poll() {
        guard isEnabled else { return }
        let count = pasteboard.changeCount
        guard count != lastChange else { return }
        lastChange = count
        let excluded = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", SystemClipboard.muleeType.rawValue
        ]
        let types = pasteboard.typeNames
        guard types.contains("public.utf8-plain-text"), types.isDisjoint(with: excluded),
              let text = pasteboard.plainText(), text.utf8.count <= OpenURLRequest.maximumBytes else { return }
        let digest = SHA256.hash(data: Data(text.utf8))
        guard !seen.contains(digest) else { return }
        let links = Self.downloadLinks(in: text)
        guard !links.isEmpty else { return }
        seen.insert(digest)
        prompt(Array(links.prefix(OpenURLRequest.maximumLinks)))
    }

    static func downloadLinks(in text: String) -> [ParsedLink] {
        let extensions: Set<String> = [
            "zip", "rar", "7z", "gz", "bz2", "xz", "tar", "tgz", "zst", "iso", "dmg", "pkg",
            "exe", "msi", "deb", "rpm", "apk", "ipa", "pdf", "epub", "mobi", "doc", "docx",
            "xls", "xlsx", "ppt", "pptx", "csv", "txt", "mp4", "mkv", "avi", "mov", "webm",
            "mp3", "flac", "wav", "m4a", "ogg", "jpg", "jpeg", "png", "gif", "webp", "torrent"
        ]
        return LinkParser.parse(text).filter { link in
            switch link {
            case .magnet, .ed2k, .video, .torrentFile: true
            case .http(let url, let thunder, _):
                thunder || (["http", "https"].contains(url.scheme?.lowercased() ?? "") && extensions.contains(url.pathExtension.lowercased()))
            }
        }
    }
}
